import 'package:flutter/material.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import '../../data/services/quiz_question_service.dart';
import '../../logic/quiz/quiz_bloc.dart';
import '../../logic/quiz/quiz_config.dart';
import '../../logic/quiz/quiz_event.dart';

/// The host chooses the game type, where the content comes from, the difficulty, the number of rounds and the time.
class QuizSetupScreen extends StatefulWidget {
  const QuizSetupScreen({super.key, this.initialMode = QuizMode.multipleChoice});

  final QuizMode initialMode;

  @override
  State<QuizSetupScreen> createState() => _QuizSetupScreenState();
}

class _QuizSetupScreenState extends State<QuizSetupScreen> {
  final _topicController = TextEditingController();

  late QuizMode _mode = widget.initialMode;
  QuizSource _source = QuizSource.bank;
  String? _category; // null = any
  int _difficulty = 0;
  late int _questionCount = _mode == QuizMode.closestMatch ? 5 : 10;
  late int _seconds = _mode == QuizMode.closestMatch ? 45 : 15;

  List<String> _categories = [];
  String? _categoriesError;
  String? _topicError;

  bool get _closest => _mode == QuizMode.closestMatch;

  @override
  void initState() {
    super.initState();
    _loadCategories();
  }

  @override
  void dispose() {
    _topicController.dispose();
    super.dispose();
  }

  Future<void> _loadCategories() async {
    try {
      final service = QuizQuestionService();
      final categories = _closest ? await service.getTermCategories() : await service.getCategories();
      if (!mounted) return;
      setState(() {
        _categories = categories;
        _categoriesError = null;
      });
    } on QuizException catch (e) {
      if (!mounted) return;
      setState(() => _categoriesError = e.message);
    }
  }

  void _changeMode(QuizMode mode) {
    setState(() {
      _mode = mode;
      _category = null;
      _categories = [];
      _categoriesError = null;
      _questionCount = _closest ? 5 : 10;
      _seconds = _closest ? 45 : 15;
      if (_closest && _difficulty == 0) _difficulty = 0;
    });
    _loadCategories();
  }

  void _create() {
    if (_source == QuizSource.ai && _topicController.text.trim().length < 3) {
      setState(() => _topicError = 'Describe the topic (at least 3 characters)');
      return;
    }

    context.read<QuizBloc>().add(CreateRoomRequested(QuizConfig(
          mode: _mode,
          source: _source,
          category: _category,
          topic: _topicController.text.trim(),
          difficulty: _source == QuizSource.ai && _difficulty == 0 ? 2 : _difficulty,
          questionCount: _questionCount,
          secondsPerQuestion: _seconds,
        )));
    Navigator.of(context).pop();
  }

  @override
  Widget build(BuildContext context) {
    // Difficulty only matters when the content is generated by AI, or for the multiple-choice bank.
    final showDifficulty = _source == QuizSource.ai || !_closest;

    return Scaffold(
      appBar: AppBar(title: const Text('New room')),
      body: ListView(
        padding: const EdgeInsets.all(24),
        children: [
          const _Label('Game type'),
          SegmentedButton<QuizMode>(
            segments: const [
              ButtonSegment(value: QuizMode.multipleChoice, label: Text('Quiz'), icon: Icon(Icons.quiz)),
              ButtonSegment(value: QuizMode.closestMatch, label: Text('Closest Match'), icon: Icon(Icons.track_changes)),
            ],
            selected: {_mode},
            onSelectionChanged: (value) => _changeMode(value.first),
          ),
          if (_closest)
            const Padding(
              padding: EdgeInsets.only(top: 8),
              child: Text(
                'You get a term and describe it in your own words. The description closest in meaning to the real definition wins the round.',
                style: TextStyle(color: Colors.grey, fontSize: 12),
              ),
            ),
          const SizedBox(height: 24),
          _Label(_closest ? 'Terms from' : 'Questions from'),
          SegmentedButton<QuizSource>(
            segments: [
              ButtonSegment(value: QuizSource.bank, label: Text(_closest ? 'Term bank' : 'Question bank'), icon: const Icon(Icons.library_books)),
              const ButtonSegment(value: QuizSource.ai, label: Text('AI generated'), icon: Icon(Icons.auto_awesome)),
            ],
            selected: {_source},
            onSelectionChanged: (value) => setState(() => _source = value.first),
          ),
          const SizedBox(height: 24),
          if (_source == QuizSource.bank) ..._bankOptions() else ..._aiOptions(),
          if (showDifficulty) ...[
            const SizedBox(height: 24),
            const _Label('Difficulty'),
            Wrap(
              spacing: 8,
              children: [
                if (_source == QuizSource.bank) _choice('Any', 0, _difficulty, (v) => setState(() => _difficulty = v)),
                _choice('Easy', 1, _difficulty, (v) => setState(() => _difficulty = v)),
                _choice('Medium', 2, _difficulty, (v) => setState(() => _difficulty = v)),
                _choice('Hard', 3, _difficulty, (v) => setState(() => _difficulty = v)),
              ],
            ),
          ],
          const SizedBox(height: 24),
          _Label(_closest ? 'Number of rounds' : 'Number of questions'),
          Wrap(
            spacing: 8,
            children: [
              for (final n in (_closest ? QuizConfig.roundCounts : QuizConfig.questionCounts))
                _choice('$n', n, _questionCount, (v) => setState(() => _questionCount = v)),
            ],
          ),
          const SizedBox(height: 24),
          _Label(_closest ? 'Time to write a description' : 'Time per question'),
          Wrap(
            spacing: 8,
            children: [
              for (final s in (_closest ? QuizConfig.writeSecondsOptions : QuizConfig.secondsOptions))
                _choice('$s s', s, _seconds, (v) => setState(() => _seconds = v)),
            ],
          ),
          const SizedBox(height: 32),
          ElevatedButton(onPressed: _create, child: const Text('Create room', style: TextStyle(fontSize: 16))),
        ],
      ),
    );
  }

  List<Widget> _bankOptions() {
    return [
      const _Label('Category'),
      if (_categoriesError != null) ...[
        Text(_categoriesError!, style: const TextStyle(color: Colors.red)),
        TextButton(onPressed: _loadCategories, child: const Text('Try again')),
      ] else
        DropdownButtonFormField<String?>(
          key: ValueKey(_mode), // the list of categories differs between the game types
          initialValue: _category,
          decoration: const InputDecoration(border: OutlineInputBorder()),
          items: [
            const DropdownMenuItem<String?>(value: null, child: Text('Any category')),
            for (final category in _categories) DropdownMenuItem<String?>(value: category, child: Text(category)),
          ],
          onChanged: (value) => setState(() => _category = value),
        ),
    ];
  }

  List<Widget> _aiOptions() {
    return [
      const _Label('Topic'),
      TextField(
        controller: _topicController,
        onChanged: (_) {
          if (_topicError != null) setState(() => _topicError = null);
        },
        decoration: InputDecoration(
          border: const OutlineInputBorder(),
          hintText: 'e.g. Human anatomy, World War II, Dart language',
          errorText: _topicError,
        ),
      ),
    ];
  }

  Widget _choice(String label, int value, int selected, ValueChanged<int> onSelected) {
    return ChoiceChip(
      label: Text(label),
      selected: selected == value,
      onSelected: (_) => onSelected(value),
      selectedColor: Colors.black,
      labelStyle: TextStyle(color: selected == value ? Colors.white : Colors.black),
      showCheckmark: false,
    );
  }
}

class _Label extends StatelessWidget {
  const _Label(this.text);

  final String text;

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 8),
      child: Text(text, style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 16)),
    );
  }
}
