import 'package:flutter/material.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import '../../data/services/database_service.dart';
import '../../data/services/profile_service.dart';
import '../../data/services/sync_service.dart';
import '../../logic/home/learning_overview.dart';
import '../../logic/learning/learning_bloc.dart';
import '../../logic/learning/learning_event.dart';
import '../learning/flashcards_screen.dart';

/// Start page: progress summary, "continue learning" shortcut and the list of game modes.
class HomeScreen extends StatefulWidget {
  const HomeScreen({super.key, required this.onOpenCards, required this.refresh});

  /// Switches the bottom navigation to the Cards tab.
  final VoidCallback onOpenCards;

  /// Notifies the screen that it became visible again, so the numbers are reloaded.
  final Listenable refresh;

  @override
  State<HomeScreen> createState() => _HomeScreenState();
}

class _HomeScreenState extends State<HomeScreen> {
  late final DatabaseService _db;
  late final SyncService _sync;
  final _profile = ProfileService();
  LearningOverview _overview = const LearningOverview.empty();

  @override
  void initState() {
    super.initState();
    _db = context.read<DatabaseService>();
    _sync = context.read<SyncService>();
    _sync.isSyncing.addListener(_onChanged);
    widget.refresh.addListener(_onChanged);
    _load();
  }

  @override
  void dispose() {
    _sync.isSyncing.removeListener(_onChanged);
    widget.refresh.removeListener(_onChanged);
    super.dispose();
  }

  void _onChanged() {
    if (mounted && !_sync.isSyncing.value) _load();
  }

  Future<void> _load() async {
    final overview = await _db.getOverview();
    if (!mounted) return;
    setState(() => _overview = overview);
  }

  Future<void> _startSession(String deckUuid) async {
    context.read<LearningBloc>().add(LoadFlashcardsForToday(deckUuid));
    await Navigator.of(context).push(
      MaterialPageRoute(builder: (_) => FlashcardsScreen(deckUuid: deckUuid)),
    );
    if (mounted) _load();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Home')),
      body: RefreshIndicator(
        onRefresh: () async {
          await _sync.syncNow();
          await _load();
        },
        child: ListView(
          padding: const EdgeInsets.all(16),
          children: [
            Text('Hi, ${_profile.nickname}!', style: const TextStyle(fontSize: 26, fontWeight: FontWeight.bold)),
            const SizedBox(height: 4),
            const Text('Ready to learn something new?', style: TextStyle(color: Colors.grey)),
            const SizedBox(height: 16),
            _buildContinueCard(),
            const SizedBox(height: 16),
            _buildProgressCard(),
            const SizedBox(height: 24),
            const Text('Game modes', style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold)),
            const SizedBox(height: 12),
            _ModeTile(
              icon: Icons.style,
              title: 'Flashcards',
              subtitle: 'Learn on your own with the Leitner system',
              onTap: widget.onOpenCards,
            ),
            const _ModeTile(icon: Icons.quiz, title: 'Quiz', subtitle: 'Play with friends, questions generated by AI'),
            const _ModeTile(icon: Icons.track_changes, title: 'Closest Match', subtitle: 'Describe the term in your own words'),
            const _ModeTile(icon: Icons.emoji_events, title: 'Daily quiz & ranking', subtitle: 'Compete for a place in the daily ranking'),
            const _ModeTile(icon: Icons.local_fire_department, title: 'Streak & rewards', subtitle: 'Collect coins for your daily streak'),
          ],
        ),
      ),
    );
  }

  Widget _buildContinueCard() {
    final recommended = _overview.recommended;

    final String title;
    final String subtitle;
    final String button;
    final VoidCallback onPressed;

    if (_overview.decks == 0) {
      title = 'Create your first deck';
      subtitle = 'Add a deck and a few cards to start learning.';
      button = 'Go to decks';
      onPressed = widget.onOpenCards;
    } else if (recommended == null) {
      title = _overview.cards == 0 ? 'Add your first cards' : 'Everything mastered!';
      subtitle = _overview.cards == 0 ? 'Your decks are empty.' : 'Add more cards to keep learning.';
      button = 'Go to decks';
      onPressed = widget.onOpenCards;
    } else {
      final toLearn = recommended.stats.perBox[0] + recommended.stats.perBox[1];
      title = 'Continue: ${recommended.deck.name}';
      subtitle = '$toLearn cards need your attention';
      button = 'Start learning';
      onPressed = () => _startSession(recommended.deck.uuid);
    }

    return Card(
      color: Colors.black,
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
      child: Padding(
        padding: const EdgeInsets.all(20),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(title, style: const TextStyle(color: Colors.white, fontSize: 20, fontWeight: FontWeight.bold)),
            const SizedBox(height: 4),
            Text(subtitle, style: const TextStyle(color: Colors.white70)),
            const SizedBox(height: 16),
            ElevatedButton(
              onPressed: onPressed,
              style: ElevatedButton.styleFrom(backgroundColor: Colors.white, foregroundColor: Colors.black),
              child: Text(button),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildProgressCard() {
    return Card(
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
      child: Padding(
        padding: const EdgeInsets.all(20),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            const Text('Your progress', style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold)),
            const SizedBox(height: 12),
            ClipRRect(
              borderRadius: BorderRadius.circular(8),
              child: LinearProgressIndicator(
                value: _overview.cards == 0 ? 0 : _overview.mastered / _overview.cards,
                minHeight: 10,
                backgroundColor: Colors.grey.shade300,
                color: Colors.green,
              ),
            ),
            const SizedBox(height: 8),
            Text('${_overview.masteredPercent}% of cards mastered', style: const TextStyle(color: Colors.grey)),
            const SizedBox(height: 16),
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceAround,
              children: [
                _Stat(value: _overview.decks, label: 'Decks'),
                _Stat(value: _overview.cards, label: 'Cards'),
                _Stat(value: _overview.mastered, label: 'Mastered'),
                _Stat(value: _overview.difficult, label: 'Difficult'),
              ],
            ),
          ],
        ),
      ),
    );
  }
}

class _Stat extends StatelessWidget {
  const _Stat({required this.value, required this.label});

  final int value;
  final String label;

  @override
  Widget build(BuildContext context) {
    return Column(
      children: [
        Text('$value', style: const TextStyle(fontSize: 22, fontWeight: FontWeight.bold)),
        Text(label, style: const TextStyle(color: Colors.grey, fontSize: 12)),
      ],
    );
  }
}

/// One game mode. Without [onTap] the mode is shown as "coming soon".
class _ModeTile extends StatelessWidget {
  const _ModeTile({required this.icon, required this.title, required this.subtitle, this.onTap});

  final IconData icon;
  final String title;
  final String subtitle;
  final VoidCallback? onTap;

  @override
  Widget build(BuildContext context) {
    final enabled = onTap != null;

    return Card(
      margin: const EdgeInsets.only(bottom: 8),
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
      child: ListTile(
        enabled: enabled,
        onTap: onTap,
        leading: CircleAvatar(
          backgroundColor: enabled ? Colors.black : Colors.grey.shade300,
          child: Icon(icon, color: enabled ? Colors.white : Colors.grey),
        ),
        title: Text(title, style: const TextStyle(fontWeight: FontWeight.w600)),
        subtitle: Text(subtitle),
        trailing: enabled
            ? const Icon(Icons.chevron_right)
            : Chip(
                label: const Text('Soon', style: TextStyle(fontSize: 12)),
                backgroundColor: Colors.grey.shade200,
                side: BorderSide.none,
                visualDensity: VisualDensity.compact,
              ),
      ),
    );
  }
}
